/**
 * Regenerate server/db/privileges-expected.ts: the owners and privileges of a database
 * provisioned and migrated with this checkout (server/db/privileges.ts), which
 * `pnpm worker restore-check` requires of a restored database.
 *
 *   pnpm db:privileges                 # against the local services (pnpm services:up)
 *   pnpm db:privileges --check         # exit 1 when the file is out of date; writes nothing
 *
 * It provisions a throwaway environment `privileges` (database aviation_privileges and its
 * logins) with the administrator URL of the local services (from .env.local, or
 * TEST_PG_ADMIN_URL), migrates it, reads the snapshot and removes the environment again.
 * Run it after adding a migration that creates objects or changes grants; the integration
 * test `restore-check` fails until the file matches. Never prints credentials.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { closeDb, createDb } from '../server/db/client.js';
import { privilegeSnapshot } from '../server/db/privileges.js';
import { APP_DIR } from './local-env.js';
import { localAdminUrl, withScratchEnvironment } from './scratch-env.js';

export const EXPECTED_FILE = resolve(APP_DIR, 'server/db/privileges-expected.ts');

/** The snapshot of a freshly provisioned and migrated database. */
export async function freshSnapshot(adminUrl: string, env = 'privileges'): Promise<string[]> {
  return withScratchEnvironment(adminUrl, env, async (urls) => {
    const db = createDb(urls.migrator, { max: 1, applicationName: 'aviation-privileges' });
    try {
      return await privilegeSnapshot(db);
    } finally {
      await closeDb(db);
    }
  });
}

export function renderExpected(lines: readonly string[]): string {
  return [
    '// Generated by `pnpm db:privileges` (scripts/privileges.ts) from a database provisioned and',
    '// migrated with this checkout; do not edit. `pnpm worker restore-check` requires a restored',
    '// database to match it (server/db/privileges.ts).',
    'export const EXPECTED_PRIVILEGES: readonly string[] = [',
    ...lines.map((l) => `  ${JSON.stringify(l)},`),
    '];',
    '',
  ].join('\n');
}

async function main(): Promise<number> {
  const check = process.argv.includes('--check');
  const text = renderExpected(await freshSnapshot(localAdminUrl()));
  const current = existsSync(EXPECTED_FILE) ? readFileSync(EXPECTED_FILE, 'utf8') : '';
  if (check) {
    if (current === text) return 0;
    console.error('server/db/privileges-expected.ts is out of date: run pnpm db:privileges');
    return 1;
  }
  if (current !== text) writeFileSync(EXPECTED_FILE, text);
  console.log(current === text ? 'privileges-expected.ts is up to date' : 'wrote server/db/privileges-expected.ts');
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().then(
    (code) => process.exit(code),
    (e: unknown) => {
      console.error(e instanceof Error ? e.message.replace(/:\/\/[^@\s]+@/g, '://<credentials>@') : String(e));
      process.exit(2);
    },
  );
}
